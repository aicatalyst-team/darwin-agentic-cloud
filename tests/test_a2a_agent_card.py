"""Tests for A2A Agent Card schema and skill definitions.

Validates that the Agent Card generated by Darwin matches the A2A v0.3.0+
specification and that all required fields are present and correctly typed.
"""

from __future__ import annotations

import json

import pytest

from darwin.agenticcloud.a2a import AgentCapabilities, AgentCard, AgentSkill
from darwin.agenticcloud.a2a.skills import (
    SKILL_IDENTITY,
    SKILL_RUN,
    SKILL_VERIFY,
    SKILLS,
    get_agent_card,
)

# -------------------------------------------------------------------
# Agent Card Schema Validation
# -------------------------------------------------------------------

class TestAgentCardSchema:
    """Validate Agent Card matches A2A v0.3.0+ schema."""

    def test_card_has_required_top_level_fields(self) -> None:
        """Agent Card must have name, description, url, version, skills."""
        card = get_agent_card()
        assert card.name
        assert card.description
        assert card.url
        assert card.version
        assert len(card.skills) >= 3

    def test_card_version_matches_package(self) -> None:
        """Version in the card must match darwin.agenticcloud.__version__."""
        from darwin import agenticcloud as dac

        card = get_agent_card()
        assert card.version == dac.__version__

    def test_card_has_provider(self) -> None:
        """Provider field must be present with organization."""
        card = get_agent_card()
        assert card.provider is not None
        assert card.provider.organization == "Darwin"
        assert card.provider.url is not None

    def test_card_has_capabilities(self) -> None:
        """Capabilities must be a valid AgentCapabilities object."""
        card = get_agent_card()
        assert isinstance(card.capabilities, AgentCapabilities)

    def test_card_default_input_output_modes(self) -> None:
        """Default I/O modes must include application/json."""
        card = get_agent_card()
        assert "application/json" in card.defaultInputModes
        assert "application/json" in card.defaultOutputModes

    def test_card_serializes_to_valid_json(self) -> None:
        """Card must serialize to valid JSON and deserialize back."""
        card = get_agent_card()
        json_str = card.model_dump_json()
        parsed = json.loads(json_str)

        assert parsed["name"] == "Darwin Agentic Cloud"
        assert "skills" in parsed
        assert len(parsed["skills"]) == 3

    def test_card_round_trip(self) -> None:
        """Card must survive a serialize → parse → reconstruct cycle."""
        card = get_agent_card()
        json_str = card.model_dump_json()
        restored = AgentCard.model_validate_json(json_str)
        assert restored == card

    def test_card_url_override(self) -> None:
        """Should accept a custom URL."""
        card = get_agent_card(url="https://custom.example.com")
        assert card.url == "https://custom.example.com"

    def test_card_version_override(self) -> None:
        """Should accept a custom version."""
        card = get_agent_card(version="99.0.0")
        assert card.version == "99.0.0"


